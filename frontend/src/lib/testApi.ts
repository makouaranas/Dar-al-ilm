/**
 * Test hooks for Playwright (docs/ARCHITECTURE.md section 14.3).
 *
 * `window.__DAR__` exists only when the URL contains `?test=1`. 3D components report into
 * this module (frame counter, renderer, reader state) whether or not the hooks are exposed;
 * the cost is a counter increment per rendered frame.
 */

import type { WebGLRenderer } from "three";

import type { LibraryState } from "@/store/useLibraryStore";

export interface RenderInfo {
  calls: number;
  triangles: number;
  textures: number;
  geometries: number;
}

export interface ReaderDebug {
  spreadIndex: number;
  flipping: boolean;
  queued: number;
  /** Pages with a GPU texture, and the quality each one currently shows. */
  textures: Record<number, "low" | "high">;
  /** Pages whose low-quality image is decoded in RAM (prefetch). */
  prefetched: number[];
  /** Pages holding at least one GPU texture (budget: 6). */
  gpuPages: number;
  /** Pages currently on screen. */
  visible: number[];
}

/** Hooks registered by components; each is undefined until its component mounts. */
export interface TestHooks {
  /** Hold the turning leaf at `progress` (starts a turn if none is running). */
  readerHold?: (progress: number, forward?: boolean) => boolean;
  /** Let a held leaf finish (past half) or fall back. */
  readerRelease?: () => boolean;
  [name: string]: unknown;
}

export interface DarTestApi {
  getState: () => LibraryState;
  /** CSS font-family values generated by next/font for Inter and Cairo. */
  fonts: { inter: string; cairo: string };
  /** Frames rendered since the page loaded (frameloop="demand" check). */
  frames: () => number;
  renderInfo: () => RenderInfo | null;
  reader: () => ReaderDebug | null;
  /** Extra hooks registered by components (camera pose, actions...). */
  extra: TestHooks;
}

declare global {
  interface Window {
    __DAR__?: DarTestApi;
  }
}

const hooks: {
  frames: number;
  renderer: WebGLRenderer | null;
  reader: (() => ReaderDebug) | null;
  extra: TestHooks;
} = { frames: 0, renderer: null, reader: null, extra: {} };

export function countFrame(): void {
  hooks.frames += 1;
}

export function registerRenderer(renderer: WebGLRenderer | null): void {
  hooks.renderer = renderer;
}

export function registerReader(reader: (() => ReaderDebug) | null): void {
  hooks.reader = reader;
}

export function registerTestHook(name: string, value: unknown): void {
  hooks.extra[name] = value;
}

export function isTestMode(): boolean {
  return typeof window !== "undefined" && new URLSearchParams(window.location.search).get("test") === "1";
}

export function installTestApi(api: Pick<DarTestApi, "getState" | "fonts">): void {
  if (!isTestMode()) return;
  window.__DAR__ = {
    ...api,
    frames: () => hooks.frames,
    renderInfo: () => {
      const info = hooks.renderer?.info;
      if (!info) return null;
      return {
        calls: info.render.calls,
        triangles: info.render.triangles,
        textures: info.memory.textures,
        geometries: info.memory.geometries,
      };
    },
    reader: () => hooks.reader?.() ?? null,
    extra: hooks.extra,
  };
}
